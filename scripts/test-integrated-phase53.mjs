import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {fileURLToPath} from "node:url";

const read=path=>readFileSync(fileURLToPath(new URL(path,import.meta.url)),"utf8");
const app=read("../src/App.tsx"),css=read("../src/styles.css");
const packageJSON=JSON.parse(read("../package.json"));
const navigation=["Início","Cardápio","Receitas","Alimentos","Compras","Perfil","Evolução"];
for(const label of navigation)assert.ok(app.includes('["'+label+'",'),"Rota ausente: "+label);
assert.match(app,/\.\.\.\(isAdmin\?\[\["Administração",ChefHat\]/,"Administração deve permanecer condicional.");
assert.match(app,/<nav aria-label="Navegação principal">/);
assert.match(app,/<nav className="mobile-nav" aria-label="Navegação móvel">/);
const currentMatches=app.match(/aria-current=\{page===name\?"page":undefined\}/g)||[];
assert.equal(currentMatches.length,2,"Navegação desktop e móvel precisam expor a página corrente.");
assert.match(app,/<a className="cc-skip-link" href="#cc-main-content">Pular para o conteúdo principal<\/a>/);
assert.match(app,/<main id="cc-main-content" tabIndex=\{-1\}>/);
assert.match(app,/<h1 ref=\{pageHeadingRef\} tabIndex=\{-1\} className="cc-page-heading">/);
assert.match(app,/if\(!hasNavigatedRef\.current\)\{hasNavigatedRef\.current=true;return;\}/);
assert.match(app,/window\.scrollTo\(0,0\);/);
assert.match(app,/pageHeadingRef\.current\?\.focus\(\{preventScroll:true\}\)/);
assert.match(app,/useEffect\(\(\)=>\{[\s\S]*?window\.scrollTo\(0,0\);[\s\S]*?\},\[page\]\)/);
assert.match(app,/<UserProfile key=\{userId\}/);
assert.match(app,/<EvolutionPanel key=\{userId\}/);
assert.match(app,/<ShoppingListSections shopping=\{shopping\}/);
assert.match(app,/page==="Receitas"/);
assert.match(app,/page==="Cardápio"/);
assert.match(css,/\.cc-skip-link:focus/);
assert.match(css,/\.sidebar nav button:focus-visible,\.mobile-nav button:focus-visible/);
assert.match(css,/\.mobile-nav button\[aria-current="page"\]/);
assert.match(css,/@media\(max-width:800px\)/);
assert.match(css,/\.mobile-nav\{overflow-x:auto/,"As abas devem continuar roláveis em telas estreitas.");
assert.doesNotMatch(app,/(?:service_role|SUPABASE_SERVICE_ROLE_KEY)/,"Nunca importar credenciais privilegiadas para o front.");
assert.ok(packageJSON.scripts.build.includes("test:integrated-phase53"),"Teste de integração precisa ser executado em todo build.");
console.log("PASS F53: navegação, orientação de foco, teclado, mobile, isolamento visual e regressão de módulos.");
