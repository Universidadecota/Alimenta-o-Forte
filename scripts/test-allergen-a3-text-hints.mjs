import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {collectAllergenTriageHints} from "../src/lib/allergenTriageHints.mjs";

const code=readFileSync(new URL("../src/AdminAllergenReviewQueue.tsx",import.meta.url),"utf8");
const suggestions=readFileSync(new URL("../src/lib/suggestions.ts",import.meta.url),"utf8");
const gate=readFileSync(new URL("../src/lib/allergenEligibility.mjs",import.meta.url),"utf8");
const detect=(text)=>collectAllergenTriageHints(text);
const has=(text,allergen)=>detect(text).hints.some(h=>h.code===allergen);
const sample="1 abacate médio, 2 ovos, páprica, sal, pimenta, cebolinha picada, 1 xícara de café preto.";
assert.equal(has(sample,"ovos"),true,"Ovo deve gerar pista editorial.");
assert.equal(has(sample,"soja"),false,"Ausência de soja literal não deve inventar um achado.");
assert.equal(has("tofu, molho shoyu e cebolinha","soja"),true,"Derivados usuais devem gerar pista, não aprovação.");
assert.equal(has("2 ovos e queijo ralado","leite"),true);
assert.equal(has("leite de coco com manteiga de amendoim","leite"),false,"Leite vegetal explícito não equivale automaticamente a leite animal.");
assert.equal(has("leite de coco e leite integral","leite"),true,"Outras ocorrências não podem ser ignoradas.");
assert.equal(has("manteiga de amendoim","amendoim"),true);
assert.equal(has("manteiga de amendoim","leite"),false);
assert.equal(has("pão integral","trigo"),true,"Pão é pista conservadora, não confirmação.");
assert.equal(has("castanha-de-caju","castanha_caju"),true);
assert.equal(has("salmão assado","peixes"),true);
assert.equal(has("camarão grelhado","crustaceos"),true);
assert.equal(has("ovosidade e inovação","ovos"),false,"Não aceitar fragmentos dentro de palavras.");
assert.equal(detect("molho pronto e caldo em cubo").composedTerms.length,2);
assert.deepEqual(detect(null),{sourceAvailable:false,hints:[],composedTerms:[]});
assert.deepEqual(detect("água e café preto").hints,[],"Sem termos continua inconclusivo.");
assert.equal(detect("água e café preto").sourceAvailable,true);
assert.match(code,/collectAllergenTriageHints/);
assert.match(code,/cc_official_recipe_source_records/);
assert.match(code,/Copiar pistas para o rascunho \(sem salvar\)/);
assert.match(code,/Nenhum termo localizado\. Isso NÃO indica ausência/);
assert.match(code,/status:"in_review"/);
assert.match(code,/cross_contact_status:"unknown"/);
assert.doesNotMatch(code,/status:"verified"/);
assert.match(suggestions,/if\(prefs\.allergies\.length\)throw new Error/);
assert.match(gate,/review\.status!=="verified"/);
console.log("OK: A3 sugere pistas textuais sem concluir ausência, não aprova receitas e preserva bloqueio de cardápios com alergias.");
