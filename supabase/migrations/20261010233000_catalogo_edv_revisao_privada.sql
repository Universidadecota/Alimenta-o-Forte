-- Inventário editorial interno. NÃO distribui texto integral nem disponibiliza receitas ao público.
create table if not exists public.source_recipe_review (
 id bigint generated always as identity primary key,
 source_name text not null,
 source_author text not null,
 recipe_title text not null,
 source_page integer not null,
 source_category text not null check(source_category in ('breakfast','main','dessert','bonus')),
 rights_status text not null default 'pending_authorization' check(rights_status in ('pending_authorization','licensed','rejected')),
 nutrition_reviewed boolean not null default false,
 created_at timestamptz not null default now(),
 unique(source_name,source_page)
);
alter table public.source_recipe_review enable row level security;
revoke all on public.source_recipe_review from anon, authenticated;
